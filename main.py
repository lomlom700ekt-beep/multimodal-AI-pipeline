from screenshot import screenshot
import base64
import json
from sqlbd import database
import time
from ask_llm_lmstudio import ask_model
import pygetwindow as gw
time.sleep(5) 
active_window = gw.getActiveWindow()
def main():
            # 1. Делаем скриншот
            file, today = screenshot()


            # 2. Читаем изображение и переводим его в Base64
            with open(file, "rb") as image_file: # read binary → «открыть файл для чтения как бинарные данные»
                image_base64 = base64.b64encode(image_file.read()).decode("utf-8")
            global active_window
            # 3.prompt
            prompt = f"""
Проанализируй скриншот и определи, чем занимается пользователь за компьютером.
Это одна запись в журнале активности, а не описание содержимого экрана.

Активное окно Windows: {active_window.title}

Главная задача — определить действие пользователя, а не действия персонажей, людей или объектов внутри отображаемого контента.

Правила определения активности:
1. Используй название активного окна как важный контекст, а скриншот — для определения того, что пользователь делает в этом приложении.
2. Различай взаимодействие с контентом и сам контент:
   - Если пользователь смотрит видео с игровым процессом, он смотрит видео, а не играет.
   - Если в видео показана игра, описывай просмотр игрового процесса, а не управление персонажем.
   - Если пользователь читает статью об игре, описывай чтение статьи, а не игру.
   - Если пользователь работает в редакторе кода, описывай работу с кодом, если это подтверждается скриншотом.
3. Не приписывай пользователю действия, которые выполняют персонажи в игре или люди в видео.
4. Не утверждай, что пользователь играет в игру, только потому, что на экране виден игровой процесс.
5. Если активное окно — браузер и на экране виден видеоплеер, отдавай предпочтение описанию просмотра видео.
6. Если невозможно надёжно определить действие пользователя, используй осторожное обобщённое описание. Не выдумывай детали.
7. Не считай одно лишь наличие открытого приложения доказательством того, что пользователь активно им пользуется.

Требования к ответу:
- Верни только корректный JSON, без Markdown и пояснений.
- Используй строго такой формат:
  {{"activity": "краткое описание действия пользователя"}}
- Значение activity должно содержать от 5 до 10 слов.
- Пиши только на русском языке.
- Не перечисляй элементы интерфейса, цвета, расположение элементов или системные показатели.
- Не переписывай текст со скриншота.
- Если определить активность невозможно, используй значение "Не удалось определить текущую активность".
"""

            model = "minicpm-v-4.7-35b-a3b"
            # 4. Формируем запрос для LM Studio
            model_output = ask_model(model,prompt,image_base64,)
            data = json.loads(model_output)

            return data, today
while True:
    data, today =  main()
    database(data, active_window.title, today)
    time.sleep(300) 
