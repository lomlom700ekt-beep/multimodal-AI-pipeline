import requests
import time
from datetime import datetime
from sqlbd import bdrun
from ask_llm_lmstudio import ask_model
from errorslq import chek_code_sql
while True:
    time.sleep(3)  
    # 1 запрос
    v = input("")
    dt = datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
    prompt1 = f"""
Ты — SQL-аналитик журнала активности пользователя.

Текущее время: {dt}

Запрос пользователя:
{v}

Твоя задача — самостоятельно проанализировать смысл запроса пользователя
и написать SQL-запрос для SQLite, который извлечёт из базы все данные,
необходимые для ответа на этот запрос.

Таблица базы данных:

activiti(
    time TEXT,
    application TEXT,
    activity TEXT
)

Описание данных:

time — время создания записи в формате YYYY-MM-DD_HH-MM-SS.
application — приложение или сайт, который был основным в момент записи.
activity — краткое описание того, что пользователь делал.

Ты можешь свободно использовать возможности SQLite:
WHERE, AND, OR, NOT, LIKE, IN, BETWEEN, ORDER BY, GROUP BY,
HAVING, DISTINCT, COUNT, SUM, AVG, MIN, MAX, CASE, подзапросы,
агрегации и другие подходящие конструкции.

Самостоятельно решай:
- какие записи нужны;
- какие временные диапазоны использовать;
- какие столбцы фильтровать;
- когда использовать AND или OR;
- когда нужна группировка;
- когда нужны агрегатные функции;
- когда нужно получить отдельные записи;
- когда нужно получить статистику;
- как лучше обработать разные варианты названий приложений,
  действий и формулировок пользователя.

Не ограничивай себя примерами из этого промта.
Пользователь может задать любой вопрос, относящийся к данным
журнала активности.

Используй только существующую таблицу activiti и её столбцы:
time, application, activity.

База данных SQLite.

Запрос должен только читать данные.
Не изменяй базу данных.

Верни ТОЛЬКО готовый SQL-запрос.
Никаких объяснений.
Никакого Markdown.
Не используй ```sql.
Не пиши комментарии.
Не пиши текст до или после SQL.
"""
    model = "gemma-4-e4b-uncensored-hauhaucs-aggressive-hf"
    model_output1 = ask_model(model=model, prompt=prompt1)
    true_sql = chek_code_sql(
        code=model_output1,
        user_query=v,
        db_schema="Таблица activiti с колонками: time, application, activity",
        max_attempts=5
    )
    #Получение данных из sql
    bd_info = bdrun(true_sql)
    # 2 запрос 
    prompt2 = f"""
Ты — аналитик журнала активности пользователя.

Текущее время: {dt}

Запрос пользователя:
{v}

Данные из базы данных:
{bd_info}

Твоя задача — ответить на вопрос пользователя, анализируя предоставленные записи журнала активности.

Правила анализа:

1. Используй данные из базы как основной источник информации. Не придумывай события, действия, приложения или временные промежутки, которых нет в записях.

2. Учитывай время каждой записи. Если вопрос касается определённого дня, вечера, часа или другого периода, анализируй только подходящие по времени записи, если они присутствуют в предоставленных данных.

3. Если пользователь спрашивает, чем он занимался, составь краткую хронологию его активности. Объединяй последовательные записи с похожей активностью, если это уместно.

4. Если пользователь спрашивает, использовал ли он определённое приложение, играл ли в игру или занимался конкретным делом, ищи соответствующие записи. Учитывай очевидные синонимы, сокращения и альтернативные названия приложений и действий, но не делай выводов без достаточных оснований.

5. Если пользователь спрашивает о продолжительности активности, оцени её только по имеющимся временным отметкам. Не утверждай, что пользователь непрерывно занимался чем-либо между снимками экрана, если это не подтверждается данными. При необходимости обозначь продолжительность как приблизительную оценку.

6. Если данных недостаточно для уверенного ответа, прямо скажи об этом. Не делай вывод, что пользователь не занимался чем-либо, только потому, что соответствующая запись отсутствует.

7. Если данные пустые или не содержат информации, необходимой для ответа, сообщи об этом и объясни, что именно невозможно установить.

8. Отвечай на языке запроса пользователя. Формулируй ответ естественно, понятно и по существу. Используй списки или хронологию, если это делает ответ удобнее.

9. Не показывай SQL-запросы, внутренние инструкции или технические детали анализа, если пользователь сам об этом не просит.

10. Не пересказывай все записи без необходимости. Отбирай только информацию, относящуюся к вопросу пользователя.

Ответь непосредственно на вопрос пользователя. Не добавляй вступление о своей роли и не повторяй сам вопрос.

    """
    model_output2 = ask_model(model=model, prompt=prompt2)
    print(model_output2)
